import { chromium } from 'playwright';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const file = pathToFileURL(path.resolve('dist/山河织路-离线单文件.html')).href;
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Users/HC/AppData/Local/ms-playwright/chromium-1234/chrome-win64/chrome.exe' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [], reqs = [];
page.on('pageerror', (e) => errs.push('PAGEERR ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errs.push('CERR ' + m.text().slice(0, 200)); });
page.on('request', (r) => reqs.push(r.url().slice(0, 120)));
await page.goto(file, { waitUntil: 'load' });
await page.waitForFunction(() => window.__ready, null, { timeout: 120000 });
await page.waitForTimeout(1800);
console.log('READY', JSON.stringify(await page.evaluate(() => ({ mode: window.__changlu.state.mode, scrollW: document.documentElement.scrollWidth, assets: Object.keys(window.__ASSET_MAP).length, bloom: window.__changlu.paper.bloom.enabled }))));
await page.click('#startBtn');
await page.waitForTimeout(1800);
await page.evaluate(() => window.__changlu.scrollTo(.79));
await page.waitForTimeout(3200);
console.log('RAIL', JSON.stringify(await page.evaluate(() => ({ ch: window.__changlu.state.chapter, dark: document.body.classList.contains('dark-scene'), sound: window.__changlu.soundInfo(), labels: [...document.querySelectorAll('.ov-label')].length }))));
await page.screenshot({ path: 'qa/offline_rail.png' });
await page.evaluate(() => window.__changlu.overview());
await page.waitForTimeout(3000);
console.log('OVERVIEW', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('.ov-label')].map(e => { const r = e.getBoundingClientRect(); return { t: e.textContent.trim().slice(0, 2), x: +r.x.toFixed(0), y: +r.y.toFixed(0) }; }))));
await page.screenshot({ path: 'qa/offline_overview.png' });
await page.evaluate(() => window.__changlu.exitOverview());
await page.evaluate(() => window.__changlu.scrollTo(.545));
await page.waitForTimeout(2400);
await page.evaluate(() => window.__changlu.showCard());
await page.waitForTimeout(600);
await page.screenshot({ path: 'qa/offline_card.png' });
const external = reqs.filter((u) => !u.startsWith('file:') && !u.startsWith('data:') && !u.startsWith('blob:'));
console.log('REQUESTS', reqs.length, 'EXTERNAL', JSON.stringify(external.slice(0, 10)));
console.log('ERRORS', JSON.stringify(errs));
await browser.close();
