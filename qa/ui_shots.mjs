import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Users/HC/AppData/Local/ms-playwright/chromium-1234/chrome-win64/chrome.exe' });
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
page.on('pageerror', e => console.log('PAGEERR', e.message));
await page.goto('http://127.0.0.1:8124/?capture=1', { waitUntil: 'networkidle' });
await page.waitForFunction(() => window.__ready, null, { timeout: 90000 });
await page.waitForTimeout(1600);
await page.evaluate(() => { window.__changlu.start(); window.__changlu.freeze(); window.__changlu.setProgress(.315); window.__changlu.settle(60); window.__changlu.showCard(); });
await page.waitForTimeout(200);
await page.screenshot({ path: 'qa/ui_card.png' });
await page.evaluate(() => { window.__changlu.hideCard(); window.__changlu.setProgress(1); window.__changlu.settle(40); window.__changlu.advance(1/24); });
await page.waitForTimeout(200);
await page.screenshot({ path: 'qa/ui_finale_prompt.png' });
await page.evaluate(() => { window.__changlu.launch(); for (let i=0;i<60;i++) window.__changlu.advance(1/24); });
await page.waitForTimeout(200);
await page.screenshot({ path: 'qa/ui_launch.png' });
await page.evaluate(() => { for (let i=0;i<60;i++) window.__changlu.advance(1/24); window.__changlu.showEnd(); });
await page.waitForTimeout(200);
await page.screenshot({ path: 'qa/ui_end.png' });
console.log('UI SHOTS DONE');
await browser.close();
