import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const browser = await chromium.launch({headless:true, executablePath:process.env.CHROME || 'C:/Users/HC/AppData/Local/ms-playwright/chromium-1234/chrome-win64/chrome.exe'});
const page = await browser.newPage({viewport:{width:1280,height:720},deviceScaleFactor:1});
const errors=[];
page.on('pageerror', e=>errors.push(e.message));
await page.goto(new URL('?capture=1',process.env.CAPTURE_URL || 'http://127.0.0.1:8137/').href, {waitUntil:'networkidle'});
await page.waitForFunction(()=>window.__ready || window.__error);
await page.waitForTimeout(1600);
await page.evaluate(()=>{__changlu.start();__changlu.setProgress(.1);__changlu.settle(40);__changlu.advance(.016);});
await page.locator('#walkBtn').click();
assert.equal(await page.locator('#walkBtn').getAttribute('aria-pressed'),'true');
const before = await page.evaluate(()=>__changlu.camera.position.toArray());
await page.keyboard.down('w');
await page.waitForTimeout(1400);
await page.keyboard.up('w');
const after = await page.evaluate(()=>__changlu.camera.position.toArray());
assert.ok(Math.hypot(after[0]-before[0],after[2]-before[2]) > .1, 'W moves the camera');
await page.keyboard.down('c');
await page.waitForTimeout(450);
const crouched = await page.evaluate(()=>__changlu.camera.position.y);
await page.keyboard.up('c');
await page.waitForTimeout(400);
assert.ok(crouched < after[1]-.3, 'C lowers the eye for close inspection');
const lookBefore = await page.evaluate(()=>__changlu.state.camLook.toArray());
await page.mouse.move(1100,350);
await page.mouse.down();
await page.mouse.move(1200,350,{steps:5});
await page.mouse.up();
await page.waitForTimeout(200);
const lookAfter = await page.evaluate(()=>__changlu.state.camLook.toArray());
assert.ok(Math.hypot(...lookAfter.map((x,i)=>x-lookBefore[i])) > .1, 'drag changes the view');
await page.locator('#memoryBtn').click();
assert.ok(await page.locator('#card').evaluate(e=>e.classList.contains('show')), 'rural memory opens while walking');
await page.locator('#cardClose').click();
await page.keyboard.press('Escape');
assert.equal(await page.locator('#walkBtn').getAttribute('aria-pressed'),'false');
await page.locator('[data-ch="1"]').click();
await page.waitForFunction(()=>__changlu.state.progress > .25,null,{timeout:10000});
assert.equal(errors.length,0,errors.join('\n'));
const result={before,after,crouched,lookBefore,lookAfter,afterTransition:await page.evaluate(()=>__changlu.info()),errors};
fs.writeFileSync(process.env.WALK_REPORT || 'qa/rural_realism/walk_check.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
await browser.close();
