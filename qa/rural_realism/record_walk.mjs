import {chromium} from 'playwright';
import fs from 'node:fs';
const dir='qa/rural_realism/recording';
fs.mkdirSync(dir,{recursive:true});
const b=await chromium.launch({headless:true,executablePath:process.env.CHROME || 'C:/Users/HC/AppData/Local/ms-playwright/chromium-1234/chrome-win64/chrome.exe'});
const c=await b.newContext({viewport:{width:1280,height:720},deviceScaleFactor:1,recordVideo:{dir,size:{width:1280,height:720}}});
const p=await c.newPage();
await p.goto('http://127.0.0.1:18371/',{waitUntil:'networkidle'});
await p.waitForFunction(()=>window.__ready);
await p.waitForTimeout(1800);
await p.locator('[data-entry="0"]').click();
await p.waitForFunction(()=>__changlu.state.chapter===0 && !__changlu.state.jumping);
await p.waitForTimeout(1200);
await p.locator('#walkBtn').click();
await p.keyboard.down('w'); await p.waitForTimeout(2600); await p.keyboard.up('w');
await p.mouse.move(950,320);await p.mouse.down();await p.mouse.move(1060,320,{steps:20});await p.mouse.up();
await p.keyboard.down('a');await p.waitForTimeout(1100);await p.keyboard.up('a');
await p.keyboard.down('w');await p.waitForTimeout(1200);await p.keyboard.up('w');
await p.keyboard.down('c');await p.waitForTimeout(850);await p.keyboard.up('c');
await p.waitForTimeout(1100);
await p.locator('#memoryBtn').click(); await p.waitForTimeout(1500);
await p.locator('#cardClose').click(); await p.waitForTimeout(700);
const video=p.video();
await c.close();
await video.saveAs(dir+'/rural_walk.webm');
await b.close();
console.log('Recorded real browser session:',dir+'/rural_walk.webm');
